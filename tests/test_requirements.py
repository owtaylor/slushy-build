from slushy_build.requirements import (
    PackageVersion,
    parse_in_file_sources,
    parse_requirements,
    parse_resolved_requirements,
    write_in_file,
)


class TestParseRequirements:
    def test_basic(self):
        text = "requests==2.31.0\nurllib3==2.0.4\n"
        result = parse_requirements(text)
        assert result == [
            PackageVersion("requests", "2.31.0"),
            PackageVersion("urllib3", "2.0.4"),
        ]

    def test_with_extras(self):
        text = "pydantic[email]==2.5.0\n"
        result = parse_requirements(text)
        assert result == [PackageVersion("pydantic", "2.5.0")]

    def test_with_markers(self):
        text = 'cffi==1.16.0 ; platform_python_implementation != "PyPy"\n'
        result = parse_requirements(text)
        assert result == [PackageVersion("cffi", "1.16.0")]

    def test_with_hashes(self):
        text = "requests==2.31.0 \\\n    --hash=sha256:abc123 \\\n    --hash=sha256:def456\n"
        result = parse_requirements(text)
        assert result == [PackageVersion("requests", "2.31.0")]

    def test_comments_and_blanks(self):
        text = "# This is a comment\n\nrequests==2.31.0\n    # indented comment\n\n"
        result = parse_requirements(text)
        assert result == [PackageVersion("requests", "2.31.0")]

    def test_pip_options_skipped(self):
        text = "--index-url https://pypi.org/simple\nrequests==2.31.0\n"
        result = parse_requirements(text)
        assert result == [PackageVersion("requests", "2.31.0")]

    def test_canonicalizes_names(self):
        text = "Jinja2==3.1.2\nsetuptools_scm==8.0.0\n"
        result = parse_requirements(text)
        assert result[0].name == "jinja2"
        assert result[1].name == "setuptools-scm"

    def test_non_matching_marker_skipped(self):
        text = 'win32-setctime==1.1.0 ; sys_platform == "win32"\n'
        result = parse_requirements(text)
        assert result == []

    def test_unpinned_skipped(self):
        text = "requests>=2.0\nflask\n"
        result = parse_requirements(text)
        assert result == []


class TestParseResolvedRequirements:
    def test_basic(self):
        text = (
            "#\n# This file is autogenerated by uv\n#\npackaging==26.2\n    # via setuptools-scm\nsetuptools==83.0.0\n"
        )
        result = parse_resolved_requirements(text)
        assert result == {"packaging": "26.2", "setuptools": "83.0.0"}

    def test_with_markers(self):
        text = 'cffi==1.16.0 ; platform_python_implementation != "PyPy"\n'
        result = parse_resolved_requirements(text)
        assert result == {"cffi": "1.16.0"}

    def test_with_extras(self):
        text = "pydantic[email]==2.5.0\n"
        result = parse_resolved_requirements(text)
        assert result == {"pydantic": "2.5.0"}

    def test_with_hashes(self):
        text = "packaging==26.2 \\\n    --hash=sha256:abc123\n"
        result = parse_resolved_requirements(text)
        assert result == {"packaging": "26.2"}


class TestWriteInFile:
    def test_writes_requirements(self, tmp_path):
        path = tmp_path / "test.in"
        write_in_file(path, ["setuptools>=67.0", "wheel"])
        assert path.read_text() == "setuptools>=67.0\nwheel\n"

    def test_writes_source_packages(self, tmp_path):
        path = tmp_path / "test.in"
        sources = [
            PackageVersion("urllib3", "2.0.4"),
            PackageVersion("requests", "2.31.0"),
        ]
        write_in_file(path, ["setuptools>=67.0"], source_packages=sources)
        text = path.read_text()
        lines = text.splitlines()
        assert lines[0] == "# slushy-build-source: requests==2.31.0"
        assert lines[1] == "# slushy-build-source: urllib3==2.0.4"
        assert lines[2] == "setuptools>=67.0"


class TestParseInFileSources:
    def test_parses_sources(self, tmp_path):
        path = tmp_path / "test.in"
        path.write_text(
            "# slushy-build-source: requests==2.31.0\n# slushy-build-source: urllib3==2.0.4\nsetuptools>=67.0\n"
        )
        result = parse_in_file_sources(path)
        assert result == [("requests", "2.31.0"), ("urllib3", "2.0.4")]

    def test_no_sources(self, tmp_path):
        path = tmp_path / "test.in"
        path.write_text("setuptools>=67.0\n")
        result = parse_in_file_sources(path)
        assert result == []

    def test_canonicalizes_names(self, tmp_path):
        path = tmp_path / "test.in"
        path.write_text("# slushy-build-source: Jinja2==3.1.2\n")
        result = parse_in_file_sources(path)
        assert result == [("jinja2", "3.1.2")]
