from slushy_build.requirements import PackageVersion
from slushy_build.resolver import find_seed_content, resolve_build_deps


class TestResolveBuildDeps:
    def test_writes_in_and_parses_output(self, mocker, tmp_path):
        def fake_compile(in_file, out_file, **kwargs):
            out_file.write_text("# autogenerated\nsetuptools==83.0.0\n    # via -r input.in\nwheel==0.41.0\n")

        mocker.patch("slushy_build.resolver.uv_pip_compile", side_effect=fake_compile)
        pkg = PackageVersion("requests", "2.31.0")
        deps = ["setuptools>=67.0", "wheel"]

        result = resolve_build_deps(pkg, deps, tmp_path)

        in_file = tmp_path / "requests-2.31.0.in"
        assert in_file.exists()
        assert "setuptools>=67.0" in in_file.read_text()
        assert "wheel" in in_file.read_text()

        assert result == {"setuptools": "83.0.0", "wheel": "0.41.0"}

    def test_passes_exclude_newer(self, mocker, tmp_path):
        def fake_compile(in_file, out_file, **kwargs):
            out_file.write_text("setuptools==83.0.0\n")

        mock_compile = mocker.patch("slushy_build.resolver.uv_pip_compile", side_effect=fake_compile)
        pkg = PackageVersion("requests", "2.31.0")

        resolve_build_deps(pkg, ["setuptools"], tmp_path, exclude_newer="2024-01-01")

        _, kwargs = mock_compile.call_args
        assert kwargs["exclude_newer"] == "2024-01-01"

    def test_seed_content_prepopulates_output(self, mocker, tmp_path):
        def fake_compile(in_file, out_file, **kwargs):
            assert out_file.read_text() == "setuptools==82.0.0\n"
            out_file.write_text("setuptools==82.0.0\n")

        mocker.patch("slushy_build.resolver.uv_pip_compile", side_effect=fake_compile)
        pkg = PackageVersion("requests", "2.31.0")

        result = resolve_build_deps(pkg, ["setuptools"], tmp_path, seed_content="setuptools==82.0.0\n")
        assert result == {"setuptools": "82.0.0"}


class TestFindSeedContent:
    def _setup_build_files(self, output_dir, groups):
        """Helper to create requirements-build files.

        groups is a list of (sources_list, txt_content) tuples.
        sources_list is a list of (name, version) tuples.
        """
        for i, (sources, txt_content) in enumerate(groups):
            suffix = "" if i == 0 else f"-{i}"
            in_lines = []
            for name, version in sources:
                in_lines.append(f"# slushy-build-source: {name}=={version}")
            in_lines.append("setuptools>=67.0")
            (output_dir / f"requirements-build{suffix}.in").write_text("\n".join(in_lines) + "\n")
            (output_dir / f"requirements-build{suffix}.txt").write_text(txt_content)

    def test_no_existing_files(self, tmp_path):
        pkg = PackageVersion("requests", "2.31.0")
        assert find_seed_content(pkg, tmp_path) is None

    def test_exact_match(self, tmp_path):
        self._setup_build_files(
            tmp_path,
            [
                (
                    [("requests", "2.31.0"), ("urllib3", "2.0.4")],
                    "setuptools==83.0.0\n",
                ),
            ],
        )
        pkg = PackageVersion("requests", "2.31.0")
        assert find_seed_content(pkg, tmp_path) == "setuptools==83.0.0\n"

    def test_name_only_match_picks_smallest_n(self, tmp_path):
        self._setup_build_files(
            tmp_path,
            [
                (
                    [("urllib3", "2.0.4")],
                    "setuptools==83.0.0\n",
                ),
                (
                    [("requests", "2.30.0")],
                    "setuptools==82.0.0\nwheel==0.41.0\n",
                ),
                (
                    [("requests", "2.29.0")],
                    "setuptools==81.0.0\n",
                ),
            ],
        )
        pkg = PackageVersion("requests", "2.31.0")
        result = find_seed_content(pkg, tmp_path)
        assert result == "setuptools==82.0.0\nwheel==0.41.0\n"

    def test_no_match_falls_back_to_n0(self, tmp_path):
        self._setup_build_files(
            tmp_path,
            [
                (
                    [("urllib3", "2.0.4")],
                    "setuptools==83.0.0\n",
                ),
            ],
        )
        pkg = PackageVersion("newpackage", "1.0.0")
        assert find_seed_content(pkg, tmp_path) == "setuptools==83.0.0\n"

    def test_exact_match_preferred_over_name_match(self, tmp_path):
        self._setup_build_files(
            tmp_path,
            [
                (
                    [("requests", "2.30.0")],
                    "old-content\n",
                ),
                (
                    [("requests", "2.31.0")],
                    "exact-content\n",
                ),
            ],
        )
        pkg = PackageVersion("requests", "2.31.0")
        assert find_seed_content(pkg, tmp_path) == "exact-content\n"

    def test_missing_txt_returns_none(self, tmp_path):
        (tmp_path / "requirements-build.in").write_text("# slushy-build-source: foo==1.0\nsetuptools>=67.0\n")
        pkg = PackageVersion("foo", "1.0")
        assert find_seed_content(pkg, tmp_path) is None
